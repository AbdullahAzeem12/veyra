  /// Retrieves the localized string for [key] based on the current profile language.
  static String tr(BuildContext context, String key) {
    final profileCtrl = AppScope.profileCtrlOf(context);
    final lang = profileCtrl?.language ?? 'English (US)';
    return get(lang, key);
  }

  /// Direct translation lookup for [lang] and [key].
  static String get(String lang, String key) {
    final dict = _translations[lang] ?? _translations['English (US)']!;
    return dict[key] ?? _translations['English (US)']![key] ?? key;
  }

  /// Whether the specified language is Right-to-Left (e.g. Arabic).
